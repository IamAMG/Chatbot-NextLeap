-- Supabase schema for sip_pipeline_rows (run in the Supabase SQL Editor).
-- Row Level Security is ENABLED so only the backend (service role / secret key)
-- can read/write via PostgREST. The frontend never holds Supabase keys.

CREATE TABLE IF NOT EXISTS public.sip_pipeline_rows (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    content TEXT NOT NULL,
    content_hash TEXT UNIQUE NOT NULL,
    title TEXT,
    author TEXT,
    date TEXT,
    votes INTEGER DEFAULT 0,
    url TEXT,
    cleaning_status TEXT NOT NULL,
    removal_reason TEXT,
    processed_by_llm INTEGER DEFAULT 0,
    behavioral_trigger TEXT,
    sentiment_polarity DOUBLE PRECISION,
    sentiment_label TEXT,
    emotional_intensity DOUBLE PRECISION,
    segment_proxy_ticket TEXT,
    segment_proxy_tenure TEXT,
    retention_dropoff_bucket TEXT,
    opportunity_score INTEGER,
    created_at TEXT,
    synced_to_supabase INTEGER DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_sip_rows_cleaning_status ON public.sip_pipeline_rows(cleaning_status);
CREATE INDEX IF NOT EXISTS idx_sip_rows_source ON public.sip_pipeline_rows(source);
CREATE INDEX IF NOT EXISTS idx_sip_rows_content_hash ON public.sip_pipeline_rows(content_hash);
CREATE INDEX IF NOT EXISTS idx_sip_rows_processed ON public.sip_pipeline_rows(processed_by_llm);

ALTER TABLE public.sip_pipeline_rows ENABLE ROW LEVEL SECURITY;

-- Service role (backend) has full access.
CREATE POLICY IF NOT EXISTS service_role_full_access
ON public.sip_pipeline_rows
FOR ALL
TO service_role
USING (true)
WITH CHECK (true);

-- Public/anon: no access (enforced by RSL).
CREATE POLICY IF NOT EXISTS anon_no_access
ON public.sip_pipeline_rows
FOR ALL
TO anon
USING (false);
